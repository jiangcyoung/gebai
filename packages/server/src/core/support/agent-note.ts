/**
 * 引擎注入消息的身份标记（DESIGN「引擎注入消息的角色约定」）：引擎/系统写入的合成消息与用户输入同角色
 * （`role: "user"`，思考类模型不接受以 assistant 结尾的请求），内容头统一以 `【智体·类别】` 起头点明来源是
 * 智体运行时——模型据此把「自动注入」与「用户指令」区分开，不会把提醒/写回当成用户的新要求去做。
 * 命令式提醒（要模型去执行动作的待办续做/收尾验证）随头附自述行，直说本条不是用户输入。
 */

/** 身份头：类别如「待办提醒」「收尾验证」「子会话「名」已合并」「定时任务「名」执行结果（成功）」「任务中断」；
 *  disclaimer=true 时附自述行（命令式提醒用）。 */
export function agentNoteHead(kind: string, disclaimer = false): string {
  const head = `【智体·${kind}】`
  return disclaimer ? `${head}（智体运行时自动注入，非用户输入）` : head
}
